const { chromium } = require('@playwright/test');
const fs = require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 page.setDefaultTimeout(15000); console.log('Opened browser'); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:3000');await page.waitForResponse(r=>r.url().includes('/api/projects'));
 await page.screenshot({path:'desktop.png',fullPage:true});
 console.log('Home captured'); await page.locator('#script').fill('Esta es una historia original. El segundo paso llega después de una pausa.');
 await page.getByRole('button',{name:'Crear storyboard'}).click();
 console.log('Create clicked'); await page.getByText('Inspector',{exact:true}).waitFor();
 await page.locator('.inspector textarea').nth(1).fill('Edición comprobada en navegador');
 await page.waitForTimeout(800);
 await page.getByRole('button',{name:'Exportar',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button',{name:'Cerrar',exact:true}).click();
 console.log('Editor ready'); await page.screenshot({path:'editor-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'editor-mobile.png',fullPage:true});
 let overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Editor mobile overflow');
 await page.getByRole('button',{name:'Volver a crear'}).click();
 await page.screenshot({path:'mobile.png',fullPage:true});
 overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow)throw Error('Create mobile overflow');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync('ui-verification.json',JSON.stringify({desktop:'1440x1100',mobile:'390x844',create:true,edit:true,exportDialog:true,horizontalOverflow:false,pageErrors:errors},null,2));
 await browser.close();console.log('UI checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
